"""
Adaptation of the map SVG generated by deebot-client to the look of a visualisation.

The SVG has no background; floor, rooms and outlines are painted by classes of a trailing ``<style>`` element
(``.u`` floor, ``.r0`` to ``.r5`` rooms, ``.o`` outlines) and the cleaning trace is one long white path.
"""

import re

# the cleaning trace: the only path that is unfilled and stroked white
_TRACE = re.compile(r'<path d="[^"]*" fill="none" stroke="#fff"[^>]*/>')
_STYLE_END = '</style>'


def parse_map_css(css: str) -> str:
    """
    Validate the ``map_css`` parameter.

    :raises ValueError: if the text contains markup
    """
    css = css.strip()
    if '<' in css:
        raise ValueError(f"map_css must be plain CSS, found '<' in {css!r}")
    return css


def process_map_svg(svg: str, css: str = '', trace: bool = True) -> str:
    """
    Apply the map options to an SVG.

    :param svg: SVG as generated by deebot-client
    :param css: rules appended to the style element of the SVG, so they override the default colours
    :param trace: ``False`` removes the cleaning trace, which makes up most of the size of the SVG
    """
    if not trace:
        svg = _TRACE.sub('', svg)
    if css:
        head, separator, tail = svg.rpartition(_STYLE_END)
        if separator:
            svg = head + css + separator + tail
    return svg
